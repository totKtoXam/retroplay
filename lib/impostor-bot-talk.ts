// Речь ботов «Предателя» на собраниях: как бот понимает чужие сообщения чата и какими словами
// говорит сам. Решает, что сказать и за кого голосовать, мозг бота (lib/impostor-bot.ts); здесь
// только разбор текста и фразы, чтобы их можно было проверить отдельно.
//
// Бот читает чат так же, как человек, — по словам. Разбор простой: имена участников в тексте и
// слова-признаки. Этого хватает, чтобы понять «я видел Васю у тела», «голосую за Васю»,
// «Вася со мной был» и «пропускаем», а на большее в чате собрания обычно и не пишут.
import { BOT_PREFIX } from './bot-levels.ts';
import type { GameMap } from './maps/types.ts';

type Point = { x: number; z: number };

/** Имя без значка бота: так его пишут люди, так бот и называет других. */
export const plainName = (name: string) => (name.startsWith(BOT_PREFIX) ? name.slice(BOT_PREFIX.length) : name).trim();

/** Отсек карты, где стоит точка; '' — коридор или карта без отсеков. */
export const zoneOf = (map: GameMap, p: Point) =>
  map.arena?.zones?.find((z) => p.x > z.minX && p.x < z.maxX && p.z > z.minZ && p.z < z.maxZ)?.name ?? '';

/** «в отсеке «Электрика»» — без склонения названия, которое в карте стоит в именительном падеже. */
export const placeOf = (zone: string) => (zone ? `в отсеке «${zone}»` : 'в коридорах');

const ACCUSE = /подозр|предател|убий|убил|видел|врёт|врет|врун|голосую|голос за|за борт|выкин|выгон|сус|\bsus\b|impost|kill|это он|это она|палится|спалил/;
// \b в JS понимает только латиницу, поэтому конец русского слова — пробел или знак препинания.
const VOUCH = /со мной|ручаюсь|чист|не предател|не он[\s.,!?]|не она[\s.,!?]|не убивал|алиби|доверяю/;
const SKIP = /скип|пропус|\bskip\b|никого не выгон|не голосу/;

export type Heard = {
  /** Кого назвали (id), в порядке появления в тексте. */
  named: string[];
  accuse: boolean;
  vouch: boolean;
  skip: boolean;
};

/**
 * Имя без окончания: в чате пишут «видел Васю», «спросите Ведущего», и точное совпадение имени
 * такие строки пропустило бы. У длинных имён отбрасываем два последних знака, у коротких — один.
 */
const stemOf = (name: string) => (name.length >= 5 ? name.slice(0, -2) : name.length >= 4 ? name.slice(0, -1) : name);

const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Что сказано в сообщении. `names` — id участников и их имена (без значка бота); автор сообщения
 * в список не входит. Имена короче двух букв не ищем: «Я» совпало бы с каждым вторым словом.
 */
export function hear(text: string, names: [string, string][]): Heard {
  const lower = ` ${text.toLowerCase().replace(/ё/g, 'е')} `;
  const named = names
    .map(([id, name]) => [id, name.toLowerCase().replace(/ё/g, 'е')] as const)
    .filter(([, name]) => name.length >= 2)
    .map(([id, name]) => {
      // Имя ищем с начала слова и с любым окончанием: «Вася», «Васю», «Васе».
      const found = new RegExp(`(^|[^0-9a-zа-я])${escapeRe(stemOf(name))}[a-zа-я]{0,3}`).exec(lower);
      return [id, found ? found.index : -1] as const;
    })
    .filter(([, at]) => at >= 0)
    .sort((a, b) => a[1] - b[1])
    .map(([id]) => id);
  const vouch = VOUCH.test(lower);
  return {
    named,
    // «Вася — не предатель» — это поручительство, а не обвинение, хотя слово «предатель» в нём есть.
    accuse: !vouch && ACCUSE.test(lower),
    vouch,
    skip: SKIP.test(lower),
  };
}

