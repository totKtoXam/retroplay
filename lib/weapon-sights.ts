/**
 * Прицельная линия оружий от первого лица.
 *
 * Раньше прицеливание было приблизительным: рука уезжала к центру экрана на
 * подобранные на глаз -0.115 по вертикали, а целиться всё равно приходилось по
 * нарисованному поверх перекрестию — модель к точке попадания отношения не
 * имела. Теперь у каждой пушки есть настоящие прицельные приспособления, и
 * `y` здесь — высота их линии над нулём модели. Сдвинув руку на -y, мы кладём
 * эту линию точно на ось камеры: целик, мушка и центр экрана оказываются на
 * одной прямой, и игрок целится сквозь оружие, а не поверх него.
 *
 * `rear` и `front` — где на этой линии стоят целик и мушка. Модель строится по
 * этим же числам, поэтому расхождение между «где нарисовано» и «куда стреляет»
 * невозможно: тест прогоняет прицеливание и проверяет, что обе метки вышли на
 * ось камеры.
 */
export type WeaponSight = {
  /** Высота линии прицела над нулём модели: рука уезжает на -y. */
  y: number;
  /**
   * Как далеко держать оружие при полном прицеливании: целик — в ладони от
   * глаза, приклад уходит за камеру. Держать дальше нельзя: тогда приклад и
   * тыльник коробки оказываются перед глазом и закрывают пол-экрана.
   */
  z: number;
  /** Z целика (ближе к глазу). */
  rear: number;
  /** Z мушки (у дула). */
  front: number;
  /** Точка вылета снаряда в координатах модели. */
  muzzle: [number, number, number];
};

export const WEAPON_SIGHTS: Record<string, WeaponSight> = {
  // Координаты — модели оружия (components/world-weapon-models.ts): начало в
  // точке хвата правой ладонью, ствол к −Z, метры. Прицел держится близко к
  // глазу, как в жизни: приклад уходит за камеру, а не закрывает пол-экрана.
  //
  // Краскомёт (карабин) несёт сразу два прицела на одной линии: механический
  // (целик на планке и штатная мушка карабина) и коллиматор между ними. Так и
  // делают в жизни — оптика не отменяет мушку, а стоит вровень с ней, поэтому
  // светящаяся точка ложится ровно на вершину мушки и целиться можно любым из двух.
  paint: { y: 0.158, z: -0.1, rear: -0.03, front: -0.415, muzzle: [0, 0.089, -0.59] },
  // Дробовик: целик на ствольной коробке и мушка-бусина у дула.
  confetti: { y: 0.067, z: -0.2, rear: -0.04, front: -0.662, muzzle: [0, 0.04, -0.75] },
  // Снайперка: линия прицела — ось оптики, от окуляра до объектива.
  sniper: { y: 0.105, z: -0.14, rear: 0, front: -0.35, muzzle: [0, 0.06, -0.865] },
  // Лайкомёт (пистолет): целик и мушка на затворе, руки вытянуты.
  like: { y: 0.082, z: -0.44, rear: 0.01, front: -0.145, muzzle: [0, 0.062, -0.165] },
};

/** Где оружие висит, пока в него не целятся: рука с рукояткой справа внизу. */
export const HIP_HOLD = { x: 0.22, y: -0.2, z: -0.25 };

export function aimHold(tool: string, aim: number) {
  const sight = WEAPON_SIGHTS[tool];
  const blend = Math.min(1, Math.max(0, aim));
  if (!sight) return { ...HIP_HOLD };
  return {
    x: HIP_HOLD.x * (1 - blend),
    y: HIP_HOLD.y + (-sight.y - HIP_HOLD.y) * blend,
    z: HIP_HOLD.z + (sight.z - HIP_HOLD.z) * blend,
  };
}

/**
 * Какой прицел стоит на краскомёте. Оба сидят на одной линии, поэтому выбор
 * ничего не меняет в баллистике — только в том, через что смотрит игрок:
 * механика не закрывает обзор рамкой, коллиматор даёт точку и подсветку целей.
 */
export type PaintSight = 'irons' | 'dot';
export const DEFAULT_PAINT_SIGHT: PaintSight = 'dot';
const PAINT_SIGHT_KEY = 'jinaly-paint-sight';

/** Варианты для колеса выбора (СКМ). */
export const PAINT_SIGHT_OPTIONS = [
  {
    id: 'irons',
    label: 'Механический',
    icon: '∧',
    color: '#9fb2c9',
  },
  {
    id: 'dot',
    label: 'Коллиматор',
    icon: '⊙',
    color: '#ff5566',
  },
];

export function readPaintSight(): PaintSight {
  if (typeof window === 'undefined') return DEFAULT_PAINT_SIGHT;
  try {
    return localStorage.getItem(PAINT_SIGHT_KEY) === 'irons'
      ? 'irons'
      : DEFAULT_PAINT_SIGHT;
  } catch {}
  return DEFAULT_PAINT_SIGHT;
}

export function writePaintSight(value: PaintSight) {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(PAINT_SIGHT_KEY, value);
  } catch {}
}
